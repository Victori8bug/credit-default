"""Generate docs/model_validation_report.md from the live results.

Organised around the three validation components US bank regulators kept in
their April 2026 model risk guidance (SR 26-2, which replaced SR 11-7):
conceptual soundness, outcomes analysis and ongoing monitoring.

Run from the project folder:  python scripts/build_validation_report.py
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from creditrisk import (fairness, features, loss, metrics, model, monitoring, pipeline, quality,  # noqa: E402
                        stress, threshold)

CUTOFF, LGD, CCF, MARGIN, LOAN = 0.14, 0.60, 0.50, 0.10, 10_000


def md_table(df, formats=None):
    formats = formats or {}
    cols = list(df.columns)
    lines = ["| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
    for _, row in df.iterrows():
        cells = [formats[c].format(row[c]) if c in formats else str(row[c]) for c in cols]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def main():
    res = pipeline.run()
    champ, chall = model.CHAMPION, model.CHALLENGER
    y, p = res.y_test, res.scores[champ]
    out = []
    w = out.append

    w("# Model validation report: credit card default model\n")
    w("Generated by `scripts/build_validation_report.py`. Every number below is recomputed from the code each time "
      "the script runs. This is a student project, not a regulatory document.\n")
    w("## 1. Purpose and scope\n")
    w(f"The model estimates the probability that a credit card account defaults next month. It supports an "
      f"approve/decline policy (approve when PD is below {CUTOFF:.0%}), expected-loss measurement and stress testing. "
      f"It was developed on {len(res.X_train):,} accounts and tested on {len(y):,} accounts held out from development.\n")

    w("## 2. Data controls\n")
    checks = quality.run_checks(res.raw)
    checks["passed"] = checks["passed"].map({True: "Pass", False: "FAIL"})
    w(md_table(checks.rename(columns={"check": "Check", "passed": "Result", "detail": "Found"})) + "\n")

    w("## 3. Conceptual soundness\n")
    w("**Design.** Logistic regression on nine engineered inputs. Demographic fields are excluded from the inputs.\n")
    coefs = model.logit_coefficients(res.fitted[champ])
    w(md_table(coefs.rename(columns={"feature": "Input", "coefficient": "Coefficient"}), {"Coefficient": "{:+.3f}"}) + "\n")
    w("**Finding 1 (open).** `paid_in_full_now` and `no_balance_now` carry positive coefficients: accounts that paid "
      "in full or had no balance are scored riskier than accounts paying the minimum on a revolving balance. The sign "
      "reflects this dataset but is counter-intuitive, and it surfaces as a reason code. It should be investigated "
      "(for example by grouping the repayment codes differently) before the reasons are relied on.\n")

    w("## 4. Outcomes analysis\n")
    rows = []
    for name, s in res.scores.items():
        sw = threshold.sweep(y, s, LOAN, MARGIN, LGD)
        rows.append({"Model": name, "Test AUC": metrics.auc(y, s), "Train AUC": metrics.auc(res.y_train, res.train_scores[name]),
                     "KS": metrics.ks_statistic(y, s), "Best profit per applicant": sw["profit_per_applicant"].max()})
    import pandas as pd
    perf = pd.DataFrame(rows)
    w(md_table(perf, {"Test AUC": "{:.3f}", "Train AUC": "{:.3f}", "KS": "{:.3f}", "Best profit per applicant": "{:,.0f}"}) + "\n")
    c_best = perf.loc[perf["Model"] == champ, "Best profit per applicant"].iloc[0]
    g_best = perf.loc[perf["Model"] == chall, "Best profit per applicant"].iloc[0]
    w(f"**Champion against challenger.** The gradient-boosting challenger earns {g_best - c_best:,.0f} more per applicant "
      f"({g_best / c_best - 1:+.0%}) at its best cutoff. The logistic regression is retained because each score is an exact, "
      f"explainable sum; the gap is the measured cost of that choice.\n")
    w("**Calibration (champion).**\n")
    cal = metrics.calibration_table(y, p)
    w(md_table(cal.rename(columns={"band": "Score band", "accounts": "Accounts", "predicted_pd": "Predicted PD",
                                   "observed_default_rate": "Observed default rate"}),
               {"Predicted PD": "{:.1%}", "Observed default rate": "{:.1%}"}) + "\n")
    ead = loss.exposure_at_default(res.X_test["BILL_AMT1"], res.X_test["LIMIT_BAL"], CCF)
    summ, realised = loss.portfolio_summary(p, ead, LGD), loss.realised_loss(y, ead, LGD)
    w(f"**Expected against realised loss.** Expected loss on the held-out accounts is {summ['expected_loss'] / 1e6:,.1f}M "
      f"against {realised / 1e6:,.1f}M on the accounts that defaulted ({summ['expected_loss'] / realised - 1:+.1%}), with "
      f"LGD {LGD:.0%} and CCF {CCF:.0%} applied to both.\n")
    now = threshold.portfolio_outcomes(y, p, CUTOFF, LOAN, MARGIN, LGD)
    w(f"**Policy outcome.** At a {CUTOFF:.0%} cutoff the policy approves {now['approval_rate']:.1%} of accounts with a "
      f"{now['bad_rate_approved']:.1%} default rate among approved accounts, against {y.mean():.1%} overall.\n")

    w("## 5. Stress testing\n")
    st = pipeline.stress_table(res.fitted[champ], res.X_test, LGD, CCF, CUTOFF)
    w(md_table(st[["scenario", "average_pd", "expected_loss", "expected_loss_vs_baseline", "approval_rate_at_cutoff"]]
               .rename(columns={"scenario": "Scenario", "average_pd": "Average PD", "expected_loss": "Expected loss",
                                "expected_loss_vs_baseline": "Change vs baseline", "approval_rate_at_cutoff": "Approval rate at cutoff"}),
               {"Average PD": "{:.1%}", "Expected loss": "{:,.0f}", "Change vs baseline": "{:+.1%}", "Approval rate at cutoff": "{:.1%}"}) + "\n")
    for s in stress.SCENARIOS[1:]:
        w(f"- **{s.name}:** {s.description}")
    w("\nScenarios are hypothetical shocks to model inputs, not forecasts linked to economic variables.\n")

    w("## 6. Ongoing monitoring\n")
    dev = res.train_scores[champ]
    rows = [{"Comparison": "Development vs held-out", "Score PSI": monitoring.psi(dev, p)}]
    worst = {}
    for s in stress.SCENARIOS[1:]:
        Xs = stress.apply(res.X_test, s)
        rows.append({"Comparison": f"Development vs {s.name.lower()} scenario", "Score PSI": monitoring.psi(dev, model.predict_pd(res.fitted[champ], Xs))})
        worst[s.name] = monitoring.feature_psi(features.engineer(res.X_train), features.engineer(Xs)).iloc[0]
    psi_df = pd.DataFrame(rows)
    psi_df["Status"] = psi_df["Score PSI"].map(monitoring.band)
    w(md_table(psi_df, {"Score PSI": "{:.3f}"}) + "\n")
    adv = worst["Adverse"]
    w(f"**Finding 2.** Under the adverse scenario the score PSI stays in the stable band while expected loss rises "
      f"{st['expected_loss_vs_baseline'].iloc[1]:+.0%}, and the input `{adv['variable']}` shows a PSI of {adv['psi']:.2f}. "
      f"Monitoring the score alone would have missed the deterioration; inputs must be monitored too.\n")

    w("## 7. Outcome testing by demographic group\n")
    w(f"Approval rates at the {CUTOFF:.0%} cutoff. Adverse impact ratio = group approval rate divided by the highest "
      "group's rate; below 0.80 is flagged for review. Groups under 500 accounts are not assessed.\n")
    approved = p < CUTOFF
    flagged = []
    for attribute in res.demographics.columns:
        t = fairness.adverse_impact(res.demographics[attribute], approved, y)
        flagged += [f"{attribute}: {g}" for g in t.loc[t["flag"] == "Review", "group"]]
        w(f"**{attribute}**\n")
        w(md_table(t.rename(columns={"group": "Group", "accounts": "Accounts", "approval_rate": "Approval rate",
                                     "observed_default_rate": "Observed default rate",
                                     "adverse_impact_ratio": "Adverse impact ratio", "flag": "Flag"}),
                   {"Approval rate": "{:.1%}", "Observed default rate": "{:.1%}", "Adverse impact ratio": "{:.2f}"}) + "\n")
    if flagged:
        w(f"**Finding 3.** Flagged for review: {', '.join(flagged)}. The attribute is not a model input, so the gap "
          "arrives through correlated repayment behaviour. A flag is a prompt to investigate, not a conclusion.\n")
    else:
        w("No group fell below the 0.80 screening ratio.\n")

    w("## 8. Limitations\n")
    w("- Existing cardholders in one market (Taiwan) over six months in 2005; not new applicants and not a normal credit cycle.\n"
      "- LGD, CCF, margin and risk-grade bands are assumptions, not estimates.\n"
      "- One 70/30 random split; no out-of-time test because the data has a single observation date.\n"
      "- The developer and the validator are the same person here. Real validation requires independence.\n")

    path = ROOT / "docs" / "model_validation_report.md"
    path.write_text("\n".join(out))
    print(f"Wrote {path}")


if __name__ == "__main__":
    main()
